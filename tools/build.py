"""Generate the per-state scripts from data/states.json, validate, and package.

Usage: python tools/build.py [--game "<EU5>/game"]
With --game, names and engine keywords are checked against that installed game.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mod'
BOM = '\ufeff'
HEADER = '# Generated by tools/build.py from data/states.json; edit those, not this file.\n'


def can_release(state):
    capitals = '\n'.join(f'\t\t\tcapital = location:{loc}' for loc in state['locations'])
    return f'''# Country scope: ROOT holds {state['name']}'s seat and could release it.
restoration_can_release_{state['tag']} = {{
\tNOT = {{ country_exists = c:{state['tag']} }}
\towns = location:{state['capital']}
\t# Never release the liberator's own capital.
\tNOT = {{
\t\tOR = {{
{capitals}
\t\t}}
\t}}
}}
'''


def release(state, subject):
    tag = state['tag']
    cores = '\n'.join(f'''\t\tlocation:{loc} = {{
\t\t\tif = {{ limit = {{ owner = root }} remove_core = root add_core = c:{tag} }}
\t\t}}''' for loc in state['locations'])
    if subject == 'papal':
        overlord = f'\t\t\tif = {{ limit = {{ country_exists = c:PAP }} make_subject_of = {{ target = c:PAP type = subject_type:restoration_crusader_state }} }}'
    else:
        overlord = '\t\t\tmake_subject_of = { target = root type = subject_type:vassal }'
    return f'''# Country scope: ROOT releases {state['name']} from the lands it holds there.
restoration_restore_{tag}_{subject} = {{
\tif = {{
\t\tlimit = {{ restoration_can_release_{tag} = yes }}
{cores}
\t\tcreate_country_from_cores_in_our_locations = c:{tag}
\t\tc:{tag} = {{
\t\t\tchange_religion = religion:catholic
\t\t\tchange_religion_for_ruler_and_family = {{ country = c:{tag} religion = religion:catholic }}
\t\t\tchange_government_type = government_type:monarchy
\t\t\tchange_culture = culture:{state['culture']}
\t\t\tif = {{ limit = {{ has_ruler = yes }} ruler = {{ change_character_culture = culture:{state['culture']} }} }}
\t\t\tset_country_rank_effect = {{ rank = country_rank:{state['rank']} }}
\t\t\tif = {{ limit = {{ owns = location:{state['capital']} }} set_capital = location:{state['capital']} }}
\t\t\tevery_owned_location = {{ add_core = c:{tag} }}
\t\t\tadd_stability = stability_extreme_bonus
{overlord}
\t\t}}
\t}}
}}
'''


def formable(state):
    tag = state['tag']
    # Jerusalem keeps vanilla's own KOJ_f too (Cyprus, Naples, military orders).
    extra = '\n\t\t\thas_reform = government_reform:military_order_reform' if tag != 'KOJ' else ''
    return f'''restoration_{tag}_f = {{
\tlevel = {state['level']}
\trequired_locations_fraction = 0.75
\trule = plausible
\tcapital_required = no

\tpotential = {{
\t\treligion = religion:catholic
\t\tOR = {{
\t\t\thas_variable = restoration_crusade_veteran{extra}
\t\t}}
\t}}

\tallow = {{
\t\towns = location:{state['capital']}
\t}}

\tname = {tag}
\tflag = {tag}
\tadjective = {tag}_ADJ
\ttag = {tag}
\tcolor = {state['color']}

\tprovinces = {{
{chr(10).join(chr(9) * 2 + p for p in state['provinces'])}
\t}}

\tform_effect = {{
\t\tadd_prestige = prestige_extreme_bonus
\t}}
}}
'''


def valid_braces(text):
    cleaned = re.sub(r'"(?:\\.|[^"\\])*"|#[^\n]*', '', text)
    depth = 0
    for ch in cleaned:
        depth += (ch == '{') - (ch == '}')
        if depth < 0:
            return False
    return depth == 0


def write(relative, text):
    path = MOD / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(BOM + HEADER + text, encoding='utf-8')


def check_game(game, states):
    """Names used by the scripts must exist in the installed game."""
    definitions = (game / 'in_game/map_data/definitions.txt').read_text(encoding='utf-8-sig')
    for state in states:
        for name in state['locations'] + state['provinces']:
            assert re.search(r'\b' + name + r'\b', definitions), name
        # The capital's province must be one the formable counts.
        province = next(p for p in state['provinces']
                        if re.search(p + r'\s*=\s*\{[^{}]*\b' + state['capital'] + r'\b', definitions))
        assert province
    vanilla = '\n'.join((game / f).read_text(encoding='utf-8-sig', errors='replace') for f in [
        'in_game/common/on_action/_hardcoded.txt', 'in_game/common/scripted_effects/country_effects.txt',
        'in_game/events/DHE/flavor_VEN.txt', 'in_game/events/government/military_order_events.txt',
        'in_game/common/formable_countries/00_formable_countries.txt'])
    for keyword in ['on_winning_war', 'casus_belli:cb_crusade', 'create_country_from_cores_in_our_locations',
                    'change_religion_for_ruler_and_family', 'set_country_rank_effect', 'make_subject_of',
                    'government_reform:military_order_reform', 'stability_extreme_bonus',
                    'prestige_extreme_bonus', 'religious_influence_extreme_bonus', 'add_religious_influence_if_valid',
                    'required_locations_fraction', 'capital_required']:
        assert keyword in vanilla, keyword
    # Checks whichever country files are present (a staged copy may hold only some).
    countries = sorted((game / 'in_game/setup/countries').glob('*.txt'))
    tags = set(re.findall(r'(?m)^(\w+)\s*=\s*\{', '\n'.join(p.read_text(encoding='utf-8-sig') for p in countries)))
    assert 'KOJ' in tags, 'vanilla KOJ identity expected'
    assert not {'CTP', 'CAN'} & tags, 'vanilla now defines CTP or CAN; pick new tags'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--game', type=Path)
    args = ap.parse_args()
    states = json.loads((ROOT / 'data/states.json').read_text(encoding='utf-8'))
    tags = [s['tag'] for s in states]
    all_locations = [loc for s in states for loc in s['locations']]
    assert len(all_locations) == len(set(all_locations)), 'a location belongs to two states'
    assert all(s['capital'] in s['locations'] for s in states)

    any_release = '\n'.join(f'\t\trestoration_can_release_{t} = yes' for t in tags)
    write('in_game/common/scripted_triggers/restoration_restorable.txt',
          '\n'.join(can_release(s) for s in states)
          + f'\n# Country scope: ROOT could release at least one crusader state.\nrestoration_can_release_any = {{\n\tOR = {{\n{any_release}\n\t}}\n}}\n')
    for subject in ['papal', 'vassal']:
        calls = '\n'.join(f'\trestoration_restore_{t}_{subject} = yes' for t in tags)
        body = '\n'.join(release(s, subject) for s in states)
        body += f'\nrestoration_restore_all_{subject} = {{\n{calls}\n}}\n'
        if subject == 'papal':
            effects = body
        else:
            effects += '\n' + body
    write('in_game/common/scripted_effects/restoration_restorable.txt', effects)
    write('in_game/common/formable_countries/restoration_formables.txt', '\n'.join(formable(s) for s in states))

    for path in MOD.rglob('*.txt'):
        text = path.read_text(encoding='utf-8-sig')
        assert valid_braces(text), path
        if 'in_game' in path.parts and ('common' in path.parts or 'events' in path.parts):
            assert path.read_bytes().startswith(b'\xef\xbb\xbf'), f'EU5 scripts need a BOM: {path}'
    localization = '\n'.join(p.read_text(encoding='utf-8-sig') for p in (MOD / 'main_menu/localization').rglob('*.yml'))
    for p in (MOD / 'main_menu/localization').rglob('*.yml'):
        assert p.read_bytes().startswith(b'\xef\xbb\xbf'), p
    keys = re.findall(r'(?m)^ ([\w.]+):', localization)
    assert len(keys) == len(set(keys)), 'duplicate localization keys'
    events = (MOD / 'in_game/events/restoration_crusade.txt').read_text(encoding='utf-8-sig')
    for key in re.findall(r'\b(?:title|desc|name|text)\s*=\s*(restoration_crusade\.[\w.]+)', events):
        assert key in keys, key
    for image in re.findall(r'image = "([^"]+)"', events):
        assert (MOD / 'main_menu' / image).read_bytes()[:4] == b'DDS ', image
    for tag in tags:
        assert f' {tag}:' in localization and f' {tag}_ADJ:' in localization, tag
    scripts = '\n'.join(p.read_text(encoding='utf-8-sig') for p in MOD.rglob('*.txt'))
    for name in re.findall(r'\b(restoration_\w+) = yes', scripts):
        assert re.search(r'(?m)^' + name + r'\s*=\s*\{', scripts), f'undefined scripted call {name}'
    assert 'own_control_core' not in scripts, 'restorable states must not exist at start'
    if args.game:
        check_game(args.game.resolve(), states)

    metadata = json.loads((MOD / '.metadata/metadata.json').read_text(encoding='utf-8'))
    manifest = {'version': metadata['version'], 'id': metadata['id'],
                'files': {p.relative_to(MOD).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in sorted(MOD.rglob('*')) if p.is_file() and p.name != 'release-manifest.json'}}
    (MOD / 'release-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    archive = dist / f'Crusader-States-Restorable-{metadata["version"]}.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for path in sorted(MOD.rglob('*')):
            if path.is_file():
                z.write(path, 'crusader_states_restorable/' + path.relative_to(MOD).as_posix())
        for relative in ['Install-Restorable.cmd', 'tools/install.ps1', 'README.md']:
            z.write(ROOT / relative, relative)
    print(json.dumps({'archive': str(archive), 'states': tags, 'files': len(manifest['files']),
                      'game_checked': bool(args.game)}, indent=2))


if __name__ == '__main__':
    main()
